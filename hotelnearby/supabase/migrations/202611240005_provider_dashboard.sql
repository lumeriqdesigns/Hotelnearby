-- Prompt 10: organisation workspace and provider dashboard data access.
-- Apply after Prompt 9. No sample organisations, properties, members or invitations are seeded.

alter table public.provider_organisations
  add column if not exists legal_name text,
  add column if not exists contact_email text,
  add column if not exists phone_number text,
  add column if not exists website_url text,
  add column if not exists address text,
  add column if not exists description text,
  add column if not exists updated_by uuid references auth.users(id);

-- Link each independently marketed property to exactly one provider organisation.
alter table public.properties
  add constraint properties_organisation_fk
  foreign key (organisation_id) references public.provider_organisations(id) on delete restrict;
create index if not exists properties_organisation_status_idx
  on public.properties(organisation_id, approval_status, updated_at desc);

-- Invitation links are generated by a provider owner and accepted only by the
-- authenticated account whose verified email matches the invitation address.
create table public.provider_invitations (
  id uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references public.provider_organisations(id) on delete cascade,
  email text not null check (email = lower(trim(email)) and length(email) <= 254),
  token_hash text not null unique,
  invited_by uuid not null references auth.users(id) on delete restrict,
  expires_at timestamptz not null,
  accepted_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  unique (organisation_id, email, accepted_at)
);
create index provider_invitations_org_idx on public.provider_invitations(organisation_id, created_at desc);
alter table public.provider_invitations enable row level security;
revoke all on public.provider_invitations from anon, authenticated;
grant select on public.provider_invitations to authenticated;
create policy "Owners read their organisation invitations" on public.provider_invitations
for select to authenticated using (public.is_provider_owner(organisation_id));

create or replace function public.accept_provider_invitation(p_token_hash text)
returns boolean language plpgsql security definer set search_path = public as $$
declare invite public.provider_invitations%rowtype;
        signed_in_email text;
begin
  if auth.uid() is null then raise exception 'Sign in before accepting an invitation'; end if;
  select lower(email) into signed_in_email from auth.users where id = auth.uid() and email_confirmed_at is not null;
  if signed_in_email is null then raise exception 'Verify your email before accepting an invitation'; end if;
  select * into invite from public.provider_invitations
    where token_hash = p_token_hash and lower(email) = signed_in_email
      and accepted_at is null and revoked_at is null and expires_at > now()
    for update;
  if invite.id is null then return false; end if;
  insert into public.provider_memberships(organisation_id,user_id,role)
    values(invite.organisation_id,auth.uid(),'staff')
    on conflict(organisation_id,user_id) do nothing;
  update public.profiles set role = 'provider_staff', updated_at = now()
    where id = auth.uid() and role = 'visitor';
  update public.provider_invitations set accepted_at = now() where id = invite.id;
  return true;
end;
$$;
revoke all on function public.accept_provider_invitation(text) from public;
grant execute on function public.accept_provider_invitation(text) to authenticated;

-- Owners can update organisation profile and manage their own staff memberships.
grant update (name, legal_name, contact_email, phone_number, website_url, address, description, updated_by)
  on public.provider_organisations to authenticated;
create policy "Owners update their organisation profile" on public.provider_organisations
for update to authenticated using (public.is_provider_owner(id))
with check (public.is_provider_owner(id) and owner_user_id = auth.uid());

grant insert, delete on public.provider_memberships to authenticated;
create policy "Owners add members to their organisation" on public.provider_memberships
for insert to authenticated with check (
  public.is_provider_owner(organisation_id) and role = 'staff'
);
create policy "Owners remove staff from their organisation" on public.provider_memberships
for delete to authenticated using (
  public.is_provider_owner(organisation_id) and role = 'staff'
);

-- Provider enquiries can be marked read/closed only by members of the owning organisation.
grant update (status) on public.property_enquiries to authenticated;
create policy "Providers update enquiry status for own properties" on public.property_enquiries
for update to authenticated using (
  exists (select 1 from public.properties p where p.id = property_id and public.is_provider_member(p.organisation_id))
) with check (
  status in ('new','read','closed') and
  exists (select 1 from public.properties p where p.id = property_id and public.is_provider_member(p.organisation_id))
);

-- Prevent providers from transferring a property to another organisation.
create or replace function public.guard_provider_property_organisation()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and public.current_platform_role() in ('provider_owner','provider_staff') then
    if new.organisation_id is null or not public.is_provider_member(new.organisation_id) then
      raise exception 'You can only manage properties belonging to your organisation';
    end if;
    if tg_op = 'UPDATE' and new.organisation_id is distinct from old.organisation_id then
      raise exception 'A property cannot be transferred between organisations';
    end if;
  end if;
  return new;
end;
$$;
create trigger properties_guard_provider_organisation
before insert or update of organisation_id on public.properties
for each row execute function public.guard_provider_property_organisation();

-- Keep room/media child records and enquiries within the property organisation.
