-- Owners create/revoke invitation records. Raw invitation tokens are never stored.
grant insert on public.provider_invitations to authenticated;
grant update (revoked_at) on public.provider_invitations to authenticated;
create policy "Owners create invitations for their organisation" on public.provider_invitations
for insert to authenticated with check (
  public.is_provider_owner(organisation_id) and invited_by = auth.uid()
  and accepted_at is null and revoked_at is null and expires_at > now()
);
create policy "Owners revoke their organisation invitations" on public.provider_invitations
for update to authenticated using (public.is_provider_owner(organisation_id))
with check (public.is_provider_owner(organisation_id) and revoked_at is not null);

-- Organisation owners may see basic profile details of members in their own organisation.
create policy "Provider members read profiles of their organisation members" on public.profiles
for select to authenticated using (
  exists (
    select 1 from public.provider_memberships target
    where target.user_id = profiles.id and public.is_provider_member(target.organisation_id)
  )
);

-- A provider may return a rejected listing for another review after correcting it.
create or replace function public.guard_provider_listing_approval()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and public.current_platform_role() in ('provider_owner','provider_staff') then
    if tg_op = 'INSERT' then
      if new.approval_status <> 'draft' or new.verification_status <> 'unverified' then
        raise exception 'New provider listings must start as draft and unverified';
      end if;
    else
      if new.approval_status is distinct from old.approval_status
        and not (old.approval_status in ('draft','rejected','approved') and new.approval_status = 'pending_review') then
        raise exception 'Only platform moderators can approve, reject or suspend listings';
      end if;
      if new.verification_status is distinct from old.verification_status then
        raise exception 'Only platform moderators can change verification status';
      end if;
    end if;
  end if;
  return new;
end;
$$;

create unique index provider_invitations_one_active_idx
  on public.provider_invitations(organisation_id, lower(email))
  where accepted_at is null and revoked_at is null;

create policy "Providers read active location hierarchy" on public.location_nodes
for select to authenticated using (
  is_active and public.has_any_platform_role(array['provider_owner','provider_staff']::public.platform_role[])
);
